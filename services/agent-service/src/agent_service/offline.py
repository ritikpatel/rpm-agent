"""Deterministic assessment and SBAR brief used when no LLM is configured or a call fails (graceful degradation).
Output uses the same schemas as the LLM path and is labelled `generated_by: offline-rules` in the console."""

from __future__ import annotations

from .policy import checkin_topic


def _latest(ctx: dict) -> dict:
    return {k: v.get("v") for k, v in ((ctx["status"] or {}).get("latest") or {}).items() if isinstance(v, dict)}


def _trend_line(ctx: dict) -> tuple[str, list[dict]]:
    t = ctx["trend"]
    if not t:
        return "no data in the last 6 h", []
    first, last = t[0], t[-1]
    parts = []
    if first.get("hr_avg") is not None and last.get("hr_avg") is not None:
        parts.append(f"mean HR {first['hr_avg']}→{last['hr_avg']}/min")
    spo2 = [b["spo2_min"] for b in t if b.get("spo2_min") is not None]
    if spo2:
        parts.append(f"lowest SpO2 {min(spo2):.0f}%")
    news = [b["news2_max"] for b in t if b.get("news2_max") is not None]
    if news:
        parts.append(f"NEWS2 max {news[0]}→{news[-1]}")
    return ", ".join(parts) or "stable", t


def assess(ctx: dict, event: dict) -> dict:
    p, st = ctx["profile"], ctx["status"] or {}
    latest = _latest(ctx)
    recent = ctx["recent"]
    hr_q = [r["hr_q"] for r in recent[-6:] if r.get("hr_q") is not None]
    if not recent:
        quality = "insufficient_data"
    elif event["type"].startswith("HR_") and hr_q and sum(q < 0.6 for q in hr_q) > len(hr_q) / 2:
        quality = "possible_artifact"
    else:
        quality = "reliable"
    concern = {"critical": "critical", "high": "high"}.get(event["severity"], "medium")
    trend, _ = _trend_line(ctx)
    home = p["care_setting"] == "home"
    actions = []
    if home:
        actions.append({"action": "SEND_CHECKIN", "reason": "confirm symptoms with the patient"})
        if event["type"].startswith("SPO2") or "spo2" not in latest:
            actions.append({"action": "REQUEST_SPOT_CHECK", "reason": "confirm oxygen saturation with a fresh reading"})
        if st.get("news2_partial"):
            actions.append({"action": "REQUEST_HOME_READINGS", "reason": "NEWS2 is partial; BP/temperature missing"})
    if concern in ("high", "critical"):
        actions.append({"action": "SET_PROFILE_CRITICAL" if concern == "critical" else "SET_PROFILE_ELEVATED",
                        "reason": "increase sampling while deterioration is assessed"})
    models = ", ".join(f"{m['model']} {m['probability']:.2f} ({m['band']}, "
                       f"{'validated' if m.get('validated') else 'unvalidated baseline'})" for m in ctx["risk"])
    return {
        "signal_quality": quality, "concern_level": concern,
        "clinical_picture": (f"{p['display_name']} ({p['age']}{p['sex']}, {p['primary_condition']}, "
                             f"{'home' if home else 'ICU'}): {event['summary']}. NEWS2 {st.get('news2')} "
                             f"({st.get('news2_band')}{', partial' if st.get('news2_partial') else ''}); "
                             f"6 h trend: {trend}."),
        "key_findings": [{"finding": event["summary"], "evidence": f"[EVENT] {event.get('evidence') or {}}"},
                         {"finding": f"6 h trend: {trend}", "evidence": "[TREND_6H]"}],
        "recommended_actions": actions,
        "model_evidence_note": f"Risk models: {models or 'unavailable'}. Unvalidated models are weak evidence.",
        "confidence": "low",
    }


def brief(ctx: dict, event: dict, assessment: dict, hits: list) -> dict:
    p, st = ctx["profile"], ctx["status"] or {}
    protocols = [h for h in hits if h.kind == "protocol"]
    summary = next((h for h in hits if h.kind == "discharge_summary"), None)
    top_doc = protocols[0].doc_id if protocols else None
    action_chunk = next((h for h in protocols if h.doc_id == top_doc and
                         h.heading.lower().startswith(("action", "response", "immediate", "if the patient"))),
                        protocols[0] if protocols else None)
    cites, rec = [], "Clinician review per RPM escalation protocol."
    if action_chunk:
        first = next((ln.strip("-0123456789. ") for ln in action_chunk.text.splitlines() if ln.strip()), "")
        rec = f"Per {action_chunk.title.split(' (')[0]}: {first} [{action_chunk.chunk_id}]"
        cites.append({"ref": action_chunk.chunk_id, "supports": "recommended escalation steps"})
    background = f"{p['primary_condition']}; {p['care_setting']} monitoring."
    if summary:
        background = f"{summary.text.splitlines()[0][:300]} [{summary.chunk_id}]"
        cites.append({"ref": summary.chunk_id, "supports": "admission and discharge history"})
    uncertain = ["Generated by offline rules (no language model available); review source data directly."]
    if st.get("news2_partial"):
        uncertain.append("NEWS2 is partial: blood pressure, respiratory rate or temperature not available.")
    if assessment["signal_quality"] != "reliable":
        uncertain.append(f"Signal quality: {assessment['signal_quality'].replace('_', ' ')}.")
    if any(not m.get("validated") for m in ctx["risk"]):
        uncertain.append("Risk scores come from unvalidated baseline models.")
    return {
        "headline": f"{event['severity'].upper()}: {event['summary']}"[:110],
        "situation": f"{p['display_name']}, {p['age']}{p['sex']}, {event['summary']} [CURRENT].",
        "background": background,
        "assessment": assessment["clinical_picture"] + " [TREND_6H]",
        "recommendation": rec,
        "citations": cites,
        "uncertainties": uncertain,
    }


def checkin_for(ctx: dict, event: dict) -> str:
    return checkin_topic(event["type"], ctx["profile"].get("primary_condition"), _latest(ctx))

"""Deterministic synthetic discharge / admission summaries from the structured record.

The extract has no clinical notes, so summaries are rendered from diagnoses, procedures, medications, last charted
vitals and abnormal labs. They are generated by template (not by an LLM) so every sentence traces to a record.
"""

from __future__ import annotations

from collections import Counter

from rpm_core.mimic import CohortMember, MimicDataset, parse_ts, to_float
from rpm_core.mimic.dataset import VITAL_ITEMS

from .documents import Document, split_sections

FOLLOW_UP = {
    "CHF": "Daily weights (report gain >2 kg in 3 days), fluid and salt restriction as advised, heart-failure clinic "
           "review within 7 days, continue guideline-directed medication as prescribed.",
    "COPD": "Target SpO2 88-92 %, inhaler technique reviewed, rescue pack per self-management plan, pulmonary "
            "rehabilitation referral, review within 7 days.",
    "Sepsis": "Complete antibiotic course as prescribed, report fever, rigors, confusion or breathlessness at once, "
              "GP review within 7 days.",
    "IHD": "Continue antiplatelet and statin as prescribed, report chest pain at rest, cardiac rehabilitation "
           "referral, cardiology review within 14 days.",
    "Stroke": "Continue secondary prevention as prescribed, BE-FAST warning signs taught, therapy follow-up "
              "arranged, stroke clinic review within 14 days.",
}


def _fmt(ts) -> str:
    return ts.strftime("%d %b %Y") if ts else "unknown"


def build_summary(ds: MimicDataset, m: CohortMember, dx_titles: dict, px_titles: dict, lab_items: dict,
                  by_subject: dict) -> Document:
    adm = next(a for a in ds.admissions_by_subject[m.subject_id] if a["hadm_id"] == m.index_hadm_id)
    stays = ds.icustays_by_hadm.get(adm["hadm_id"], [])
    icu = stays[-1] if stays else None
    rows = by_subject[m.subject_id]
    sex = {"M": "man", "F": "woman"}.get(m.sex, "patient")
    in_icu = m.care_setting == "icu"
    title = f"{'ICU admission' if in_icu else 'Discharge'} summary — {m.display_name}"

    lines = ["## Admission",
             f"{m.display_name}, a {m.age}-year-old {sex}, was admitted on {_fmt(m.shift(parse_ts(adm['admittime'])))} "
             f"via {adm.get('admission_location', 'unknown').lower()} ({adm.get('admission_type', '').lower()}) "
             f"with {m.condition}."]
    if icu:
        lines.append(f"ICU care in the {icu.get('first_careunit')} for {to_float(icu.get('los')) or 0:.1f} days.")
    if in_icu:
        lines.append("The patient remains in the ICU under continuous bedside monitoring.")
    else:
        lines.append(f"Length of stay {m.los_days:.0f} days. Discharged on {_fmt(m.discharge_at)} to "
                     f"{(m.discharge_disposition or 'home').lower()} with remote monitoring (smartwatch).")
    if m.prior_admissions_12m:
        lines.append(f"{m.prior_admissions_12m} other admission(s) in the preceding 12 months.")

    dx = sorted((r for r in rows["diagnoses_icd"] if r["hadm_id"] == adm["hadm_id"]), key=lambda r: int(r["seq_num"]))
    lines += ["## Diagnoses"] + [f"- {dx_titles.get((r['icd_code'], r['icd_version']), r['icd_code'])} "
                                 f"(ICD-{r['icd_version']} {r['icd_code']})" for r in dx[:8]]
    px = [r for r in rows["procedures_icd"] if r["hadm_id"] == adm["hadm_id"]]
    if px:
        lines += ["## Procedures"] + [f"- {px_titles.get((r['icd_code'], r['icd_version']), r['icd_code'])}"
                                      for r in px[:6]]
    meds = Counter((r["drug"], r.get("route") or "", r.get("doses_per_24_hrs") or "")
                   for r in rows["prescriptions"] if r["hadm_id"] == adm["hadm_id"] and r.get("drug"))
    if meds:
        lines += ["## Medications"] + [f"- {d} {route}".rstrip() + (f", {n}x daily" if n else "")
                                       for (d, route, n), _ in meds.most_common(10)]

    last: dict[str, tuple] = {}
    for r in ds.chartevents_by_stay.get(icu["stay_id"], []) if icu else []:
        if r["itemid"] in VITAL_ITEMS and r["valuenum"]:
            key = VITAL_ITEMS[r["itemid"]]
            if key not in last or r["charttime"] > last[key][0]:
                last[key] = (r["charttime"], float(r["valuenum"]))
    if last:
        v = {k: val for k, (_, val) in last.items()}
        vitals = ", ".join(f"{label} {v[k]:.0f}{unit}" for k, label, unit in (
            ("heart_rate", "HR", "/min"), ("spo2", "SpO2", " %"), ("resp_rate", "RR", "/min"),
            ("sbp", "SBP", " mmHg")) if k in v)
        if "temp" in v:
            vitals += f", temperature {v['temp']:.1f} °C"
        lines += ["## Observations", f"Last charted vital signs: {vitals}."]
    abnormal: dict[str, tuple] = {}
    for r in rows["labevents"]:
        if r["hadm_id"] == adm["hadm_id"] and r.get("flag") == "abnormal" and r.get("valuenum"):
            label = lab_items.get(r["itemid"], {}).get("label", r["itemid"])
            if label not in abnormal or r["charttime"] > abnormal[label][0]:
                abnormal[label] = (r["charttime"], float(r["valuenum"]), r.get("ref_range_lower"),
                                   r.get("ref_range_upper"))
    if abnormal:
        lines.append("Abnormal laboratory results: " + "; ".join(
            f"{k} {val:g} (ref {lo}-{hi})" for k, (_, val, lo, hi) in list(abnormal.items())[:6]) + ".")
    lines += ["## Follow-up plan", FOLLOW_UP.get(m.condition, "Clinical review within 7 days."),
              "Escalation according to the RPM protocols (see P-NEWS2 and condition-specific protocols)."]

    content = "\n".join(lines)
    doc_id = f"DS-{m.patient_id}"
    return Document(doc_id, "discharge_summary", title, f"generated from structured record ({m.index_hadm_id})",
                    "synthetic patient record (derived)", content, m.patient_id, split_sections(doc_id, content))


def build_all(ds: MimicDataset, members: list[CohortMember]) -> list[Document]:
    dx_titles = {(r["icd_code"], r["icd_version"]): r["long_title"] for r in ds.table("d_icd_diagnoses")}
    px_titles = {(r["icd_code"], r["icd_version"]): r["long_title"] for r in ds.table("d_icd_procedures")}
    lab_items = ds.dictionary("d_labitems", "itemid")
    by_subject: dict = {}
    for table in ("diagnoses_icd", "procedures_icd", "prescriptions", "labevents"):
        for r in ds.table(table):
            by_subject.setdefault(r["subject_id"], {t: [] for t in
                                                    ("diagnoses_icd", "procedures_icd", "prescriptions", "labevents")})
            by_subject[r["subject_id"]][table].append(r)
    for m in members:
        by_subject.setdefault(m.subject_id, {t: [] for t in
                                             ("diagnoses_icd", "procedures_icd", "prescriptions", "labevents")})
    return [build_summary(ds, m, dx_titles, px_titles, lab_items, by_subject) for m in members]
